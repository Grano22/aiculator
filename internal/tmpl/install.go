// generatedMarker identifies a directory this package wrote, and so may replace.
const generatedMarker = ".aiculator-generated"

// InstallOptions configures Install.
type InstallOptions struct {
	Skill      skillpack.Options // Scope, harnesses and targets, exactly as skill --install.
	Vars       map[string]string
	Version    string
	PerHarness bool // Render a separate copy per harness, so {{ harness.id }} can differ.
}

// names returns template names matching the patterns.
func (s *Set) names(patterns []string) ([]string, error) {
	list, err := s.List()
	if err != nil {
		return nil, err
	}
	names := make([]string, len(list))
	for i, t := range list {
		names[i] = t.Name
	}
	return skillpack.Match(patterns, names)
}

// Install renders matching templates into skills, then installs them like any skill.
func (s *Set) Install(o InstallOptions) ([]skillpack.Action, error) {
	selected, err := s.names(o.Skill.Patterns)
	if err != nil {
		return nil, err
	}
	base := o.Skill.Base()
	var acts []skillpack.Action
	for _, name := range selected {
		t, err := s.Get(name)
		if err != nil {
			return acts, err
		}
		if !o.PerHarness {
			dest := filepath.Join(base, filepath.FromSlash(skillpack.CanonicalDir), name)
			a, err := s.write(t, Context{Vars: o.Vars, Version: o.Version}, dest, "canonical")
			acts = append(acts, a)
			if err != nil {
				return acts, err
			}
			if a.What == "conflict" {
				continue // Leave the user's own skill alone, and do not link it either.
			}
			one := o.Skill
			one.Patterns = []string{name}
			more, err := skillpack.Install(one)
			acts = append(acts, more...)
			if err != nil {
				return acts, err
			}
			continue
		}
		done := map[string]bool{}
		for _, h := range o.Skill.Harnesses {
			var root string
			if o.Skill.Global {
				root = o.Skill.Expand(h.GlobalSkillsDir)
			} else {
				root = filepath.Join(base, filepath.FromSlash(h.SkillsDir))
			}
			if done[root] {
				continue
			}
			done[root] = true
			// Harnesses that share .agents/skills cannot have separate copies, so
			// they get the neutral form.
			c := Context{Vars: o.Vars, Version: o.Version, Harness: &h}
			if strings.HasSuffix(filepath.ToSlash(root), skillpack.CanonicalDir) {
				c.Harness = nil
			}
			a, err := s.write(t, c, filepath.Join(root, name), h.ID)
			acts = append(acts, a)
			if err != nil {
				return acts, err
			}
		}
		for _, p := range o.Skill.Paths {
			a, err := s.write(t, Context{Vars: o.Vars, Version: o.Version}, filepath.Join(o.Skill.Expand(p), name), p)
			acts = append(acts, a)
			if err != nil {
				return acts, err
			}
		}
	}
	return acts, nil
}

// write renders into a temporary directory, lints it, and only then replaces the
// destination, so that a template with a mistake cannot damage an installed skill.
func (s *Set) write(t Template, c Context, dest, label string) (skillpack.Action, error) {
	act := skillpack.Action{Skill: t.Name, Target: label}
	info, err := os.Lstat(dest)
	exists := err == nil
	if exists {
		_, merr := os.Stat(filepath.Join(dest, generatedMarker))
		if info.Mode()&os.ModeSymlink != 0 || merr != nil {
			act.What, act.Detail = "conflict", dest+" is not generated by a template and was left alone"
			return act, nil
		}
	}
	text, err := s.Render(t, c)
	if err != nil {
		return act, err
	}
	if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
		return act, err
	}
	tmp, err := os.MkdirTemp(filepath.Dir(dest), ".render-")
	if err != nil {
		return act, err
	}
	defer os.RemoveAll(tmp)
	staged := filepath.Join(tmp, t.Name)
	if err := os.MkdirAll(staged, 0o755); err != nil {
		return act, err
	}
	if t.dir != "" {
		if err := copySiblings(t.dir, staged); err != nil {
			return act, err
		}
	}
	if t.root == "" {
		if err := copyBundledSiblings(t, staged); err != nil {
			return act, err
		}
	}
	if err := os.WriteFile(filepath.Join(staged, "SKILL.md"), []byte(text), 0o644); err != nil {
		return act, err
	}
	issues := skillpack.Lint(staged)
	if skillpack.IssuesHaveErrors(issues) {
		var msgs []string
		for _, i := range issues {
			if i.Level == skillpack.LevelError {
				msgs = append(msgs, i.Msg)
			}
		}
		return act, fmt.Errorf("%s renders to an invalid skill: %s", t.Name, strings.Join(msgs, "; "))
	}
	if err := os.WriteFile(filepath.Join(staged, generatedMarker), []byte("Generated from "+t.Source+". Edit the template, not this directory.\n"), 0o644); err != nil {
		return act, err
	}
	if exists {
		if err := os.RemoveAll(dest); err != nil {
			return act, err
		}
	}
	if err := os.Rename(staged, dest); err != nil {
		return act, err
	}
	act.What, act.Detail = "rendered", dest
	return act, nil
}

// templateFile reports whether a file is the template itself, not a sibling to copy.
func templateFile(name string) bool { return slices.Contains(skillNames, name) }

func copySiblings(src, dst string) error {
	return filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, p)
		if err != nil {
			return err
		}
		out := filepath.Join(dst, rel)
		if d.IsDir() {
			return os.MkdirAll(out, 0o755)
		}
		if templateFile(rel) || !d.Type().IsRegular() {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		info, err := d.Info()
		if err != nil {
			return err
		}
		return os.WriteFile(out, b, info.Mode().Perm())
	})
}

func copyBundledSiblings(t Template, dst string) error {
	root := "library/templates/" + t.Name
	return fs.WalkDir(library, root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel := strings.TrimPrefix(strings.TrimPrefix(p, root), "/")
		if rel == "" || templateFile(rel) {
			return nil
		}
		out := filepath.Join(dst, filepath.FromSlash(rel))
		if d.IsDir() {
			return os.MkdirAll(out, 0o755)
		}
		b, err := library.ReadFile(p)
		if err != nil {
			return err
		}
		return os.WriteFile(out, b, 0o644)
	})
}

// Check compares generated skills with what their templates produce now, so that CI
// can catch a template that was changed without re-rendering.
func (s *Set) Check(o InstallOptions) ([]string, error) {
	selected, err := s.names(o.Skill.Patterns)
	if err != nil {
		return nil, err
	}
	var stale []string
	for _, name := range selected {
		dest := filepath.Join(o.Skill.Base(), filepath.FromSlash(skillpack.CanonicalDir), name)
		if _, err := os.Stat(filepath.Join(dest, generatedMarker)); err != nil {
			if errors.Is(err, os.ErrNotExist) {
				continue // Not rendered here, so there is nothing to be out of date.
			}
			return stale, err
		}
		t, err := s.Get(name)
		if err != nil {
			return stale, err
		}
		want, err := s.Render(t, Context{Vars: o.Vars, Version: o.Version})
		if err != nil {
			return stale, err
		}
		got, err := os.ReadFile(filepath.Join(dest, "SKILL.md"))
		if err != nil {
			return stale, err
		}
		if string(got) != want {
			stale = append(stale, name)
		}
	}
	return stale, nil
}

// New creates a starter template showing the main features.
func New(base, name string) (string, error) {
	if strings.ContainsAny(name, `/\`) || strings.HasPrefix(name, ".") || name == "" {
		return "", fmt.Errorf("invalid template name %q", name)
	}
	dir := filepath.Join(base, ".agents", "templates")
	path := filepath.Join(dir, name+".md.j2")
	if _, err := os.Stat(path); err == nil {
		return "", fmt.Errorf("%s already exists", path)
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	body := `---
template:
  vars:
    retries: 3
name: ` + name + `
description: TODO say what this skill does and when to use it, with words people actually use.
metadata:
  version: "0.1.0"
---

# ` + name + `

<Toc />

<Directive id="main-rule">State the most important rule here.</Directive>

{% if harness.id == "claude" %}
This line appears only when rendered for Claude Code, with --per-harness.
{% endif %}

<Subagents use="when" when="the work splits into independent parts" not_when="the steps depend on each other" />

<Backoff timeout="120s" retries="{{ retries }}" />

<OutputFormat>
Done: what changed
</OutputFormat>

<Flow name="main">
<Step n="1" title="First" ask="Is this the right goal?" subagent="Do not ask. Use the task you were given.">Say what you will do.</Step>

<Step n="2" title="Second">Do it.</Step>
</Flow>
`
	return path, os.WriteFile(path, []byte(body), 0o644)
}
