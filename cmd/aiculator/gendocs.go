package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"

	"aiculation/internal/harness"
)

// genDocsCmd writes the reference pages from the code, so that they cannot drift.
// TestReferenceDocsAreCurrent fails if the committed pages are out of date.
func genDocsCmd() *cobra.Command {
	var out string
	cmd := &cobra.Command{
		Use:    "gen-docs",
		Short:  "Write the reference pages of the documentation",
		Hidden: true,
		RunE: func(*cobra.Command, []string) error {
			if err := os.MkdirAll(out, 0o755); err != nil {
				return err
			}
			if err := os.WriteFile(filepath.Join(out, "cli.md"), []byte(cliReference()), 0o644); err != nil {
				return err
			}
			return os.WriteFile(filepath.Join(out, "harnesses.md"), []byte(harnessReference()), 0o644)
		},
	}
	cmd.Flags().StringVar(&out, "out", "docs/reference", "output directory")
	return cmd
}

const generatedNote = "<!-- Generated by aiculator gen-docs. Do not edit by hand. -->\n\n"

func cliReference() string {
	var b strings.Builder
	b.WriteString(generatedNote + "# CLI reference\n\nEvery command, generated from the program itself. Run any command with `--help` to see the same text.\n")
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		for _, sub := range c.Commands() {
			if sub.Hidden || !sub.IsAvailableCommand() || sub.Name() == "help" || sub.Name() == "completion" {
				continue
			}
			fmt.Fprintf(&b, "\n## `%s`\n\n%s\n", sub.CommandPath(), sub.Short)
			if sub.Long != "" {
				fmt.Fprintf(&b, "\n%s\n", sub.Long)
			}
			fmt.Fprintf(&b, "\n```text\n%s\n```\n", sub.UseLine())
			if sub.Example != "" {
				fmt.Fprintf(&b, "\n**Examples**\n\n```text\n%s\n```\n", sub.Example)
			}
			if f := sub.LocalFlags().FlagUsages(); strings.TrimSpace(f) != "" {
				fmt.Fprintf(&b, "\n**Flags**\n\n```text\n%s```\n", f)
			}
			walk(sub)
		}
	}
	walk(rootCmd())
	return b.String()
}

func harnessReference() string {
	var b strings.Builder
	b.WriteString(generatedNote + "# Harness reference\n\nGenerated from the registry in `internal/harness`.\n\n")
	b.WriteString("\"Docs\" means the skill and MCP facts come from that harness's own documentation. \"Table\" means the skill path comes from a community table and the ACP command from the ACP registry, so treat it as a starting point.\n\n")
	b.WriteString("| ID | Name | Skills | MCP config | ACP command | Facts from |\n|---|---|---|---|---|---|\n")
	for _, h := range harness.All() {
		skills := "`" + h.SkillsDir + "` (link)"
		if h.ReadsAgents {
			skills = "`.agents/skills`"
		}
		mcp := "Shell route"
		if h.MCPFile != "" {
			mcp = "`" + h.MCPFile + "`"
		}
		acp := "None"
		if len(h.ACP) > 0 {
			acp = "`" + strings.Join(h.ACP, " ") + "`"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n", h.ID, h.Name, skills, mcp, acp, h.Source)
	}
	return b.String()
}
