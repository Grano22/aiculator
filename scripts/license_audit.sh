#!/bin/sh
# Audits the licenses of every module linked into the shipped binaries, and writes
# THIRD_PARTY_NOTICES.md with each license's full text, plus any NOTICE file, as
# these licenses require. Exits non-zero if anything is not on the allowlist.
set -eu
cd "$(dirname "$0")/.."
out=THIRD_PARTY_NOTICES.md
tmp=$(mktemp)
fail=0
{
  echo "# Third-party notices"
  echo
  echo "The swarm binary links the following modules. Generated by scripts/license_audit.sh."
  echo
} > "$tmp"
mods=$(go list -deps -f '{{if not .Standard}}{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}{{end}}' ./cmd/swarm | sort -u)
printf '%s\n' "$mods" | while read -r path version dir; do
  [ -n "$path" ] || continue
  file=$(ls "$dir" | grep -iE '^(licen[cs]e|copying)' | head -1 || true)
  if [ -z "$file" ]; then echo "NO LICENSE FILE: $path" >&2; echo 1 > "$tmp.fail"; continue; fi
  text=$(head -c 4000 "$dir/$file" | tr '\n' ' ')
  case "$text" in
    *"GNU AFFERO"*|*"GNU GENERAL"*|*"GNU LESSER"*|*"Business Source"*|*"Server Side Public"*|*"Commons Clause"*) kind=DENIED ;;
    *"Apache License"*) kind=Apache-2.0 ;;
    *"Mozilla Public"*) kind=MPL-2.0 ;;
    *"Redistribution and use"*) kind=BSD ;;
    *"Permission is hereby granted"*) kind=MIT ;;
    *"Permission to use, copy"*) kind=ISC ;;
    *) kind=UNKNOWN ;;
  esac
  printf '%-11s %s %s\n' "$kind" "$path" "$version"
  case "$kind" in DENIED|UNKNOWN) echo 1 > "$tmp.fail" ;; esac
  { echo "## $path $version ($kind)"; echo; echo '```'; cat "$dir/$file"; echo '```'; echo; } >> "$tmp"
  notice=$(ls "$dir" | grep -iE '^notice' | head -1 || true)
  if [ -n "$notice" ]; then { echo "### NOTICE"; echo; echo '```'; cat "$dir/$notice"; echo '```'; echo; } >> "$tmp"; fi
done
if [ -f "$tmp.fail" ]; then rm -f "$tmp" "$tmp.fail"; echo "LICENSE AUDIT FAILED" >&2; exit 1; fi
mv "$tmp" "$out"
echo "license audit passed; wrote $out"
